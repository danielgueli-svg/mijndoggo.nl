export const walkKindLabels: Record<WalkSpotKind, string> = {
  strand: "Strand",
  bos: "Bos",
  park: "Park",
  duin: "Duin",
  uiterwaard: "Uiterwaard",
};

function spotMatchesQuery(spot: WalkSpot, query: string): boolean {
  const q = fold(query);
  if (!q) return false;
  const hay = [spot.city, spot.name, ...spot.aliases].map(fold).join(" ");
  return hay.includes(q);
}

/** Plekken bij de gezochte stad, plus altijd strand en bos. */
export function walkSpotsForCity(query: string): {
  nearby: WalkSpot[];
  always: WalkSpot[];
} {
  const nearby = query.trim()
    ? CITY_WALK_SPOTS.filter((spot) => spotMatchesQuery(spot, query))
    : [];
  return { nearby, always: ALWAYS_WALK_SPOTS };
}

export function allWalkSpots(): WalkSpot[] {
  return [...CITY_WALK_SPOTS, ...ALWAYS_WALK_SPOTS];
}

export function findWalkSpot(id: string): WalkSpot | undefined {
  return allWalkSpots().find((spot) => spot.id === id);
}

/** Zoek uitlaatplekken op naam, stad of soort. */
export function searchWalkSpots(query: string): WalkSpot[] {
  const q = fold(query);
  if (!q) return [];
  return allWalkSpots().filter((spot) => {
    const hay = [spot.name, spot.city, walkKindLabels[spot.kind], ...spot.aliases]
      .map(fold)
      .join(" ");
    return hay.includes(q);
  });
}
